import fs from 'node:fs';
import path from 'node:path';
import { validateExtensionManifest } from '../core/src/config-engine/index';

function resolveTenantPackageDirs(repoRoot: string): string[] {
  const configured = process.env.PLATFORM_TENANT_PACKAGE_DIR?.trim();
  if (configured) {
    return [configured];
  }
  const entries = fs.readdirSync(repoRoot, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory() && entry.name.startsWith('client-'))
    .map((entry) => entry.name)
    .sort()
    .filter((dirName) =>
      fs.existsSync(path.join(repoRoot, dirName, 'config', 'base.json')),
    );
}

function generateExtensionRegistry(): void {
  const repoRoot = process.cwd();
  const outDir = path.join(repoRoot, 'src', 'platform', 'generated');
  const outFile = path.join(outDir, 'extensionRegistry.ts');

  const packageDirs = resolveTenantPackageDirs(repoRoot);
  const imports: string[] = [];
  const moduleVarNames: string[] = [];
  let idx = 0;

  for (const pkgDir of packageDirs) {
    const baseConfigPath = path.join(repoRoot, pkgDir, 'config', 'base.json');
    if (!fs.existsSync(baseConfigPath)) continue;
    const baseConfig = JSON.parse(fs.readFileSync(baseConfigPath, 'utf8')) as {
      enabledExtensions?: unknown;
    };
    const enabledSet = new Set<string>(
      Array.isArray(baseConfig.enabledExtensions)
        ? baseConfig.enabledExtensions.filter(
            (x): x is string => typeof x === 'string',
          )
        : [],
    );

    const extensionsRoot = path.join(repoRoot, pkgDir, 'extensions');
    if (!fs.existsSync(extensionsRoot)) continue;

    const extEntries = fs
      .readdirSync(extensionsRoot, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();

    for (const extDirName of extEntries) {
      const extDir = path.join(extensionsRoot, extDirName);
      const manifestPath = path.join(extDir, 'manifest.json');
      if (!fs.existsSync(manifestPath)) continue;

      const rawManifest = JSON.parse(
        fs.readFileSync(manifestPath, 'utf8'),
      ) as Record<string, unknown>;
      const candidateId =
        typeof rawManifest.id === 'string' && rawManifest.id.trim()
          ? rawManifest.id.trim()
          : extDirName;
      if (!enabledSet.has(candidateId) && !enabledSet.has(extDirName)) {
        continue;
      }

      const validated = validateExtensionManifest(rawManifest);
      if (!enabledSet.has(validated.id)) {
        continue;
      }

      const entryCandidates = [
        path.join(extDir, 'src', 'index.ts'),
        path.join(extDir, 'index.ts'),
        path.join(extDir, 'src', 'index.js'),
        path.join(extDir, 'index.js'),
      ];
      const entryFile = entryCandidates.find((c) => fs.existsSync(c));
      if (!entryFile) {
        throw new Error(
          `EXTENSION_ENTRY_NOT_FOUND: Enabled extension "${validated.id}" in "${extDir}" has no entry module.`,
        );
      }

      const relImport = path
        .relative(outDir, entryFile)
        .replace(/\\/g, '/')
        .replace(/\.(ts|js)$/, '');
      const varName = `extModule_${idx++}`;
      imports.push(`import * as ${varName} from '${relImport}';`);
      moduleVarNames.push(varName);
    }
  }

  const lines: string[] = [
    '// AUTO-GENERATED by scripts/generate-extension-registry.ts — DO NOT EDIT MANUALLY.',
    "import type { PlatformExtension } from '@platform/core-api';",
    ...imports,
    '',
    'function isPlatformExtension(value: unknown): value is PlatformExtension {',
    "  if (!value || typeof value !== 'object') return false;",
    '  const candidate = value as Record<string, unknown>;',
    '  return (',
    "    typeof candidate.manifest === 'object' &&",
    '    candidate.manifest !== null &&',
    "    typeof (candidate.manifest as Record<string, unknown>).id === 'string' &&",
    "    typeof candidate.hooks === 'object' &&",
    '    candidate.hooks !== null',
    '  );',
    '}',
    '',
    'const registry: Record<string, PlatformExtension> = {};',
    `for (const mod of [${moduleVarNames.join(', ')}]) {`,
    '  for (const exportedValue of Object.values(mod)) {',
    '    if (isPlatformExtension(exportedValue)) {',
    '      registry[exportedValue.manifest.id] = exportedValue;',
    '    }',
    '  }',
    '}',
    '',
    'export const BUNDLED_TENANT_EXTENSIONS: Readonly<Record<string, PlatformExtension>> =',
    '  Object.freeze(registry);',
    '',
  ];

  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
}

generateExtensionRegistry();
