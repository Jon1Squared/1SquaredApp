import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { HostingMode, PlatformEnvironment } from '../core/src/api/index';
import {
  loadAndValidateTenantConfig,
  validateExtensionManifest,
} from '../core/src/config-engine/index';

export interface GenerateExtensionRegistryOptions {
  repoRoot?: string;
  env?: Record<string, string | undefined>;
  argv?: readonly string[];
  outDir?: string;
}

export interface GenerateExtensionRegistryResult {
  writtenFile: string;
  bundledExtensionIds: string[];
}

function resolveEnvironmentOverlayPath(
  pkgRoot: string,
  platformEnv: PlatformEnvironment,
): string | null {
  const candidates = [
    path.join(pkgRoot, 'config', 'environments', `${platformEnv}.json`),
    path.join(pkgRoot, 'config', `${platformEnv}.json`),
  ];
  return candidates.find((candidate) => fs.existsSync(candidate)) ?? null;
}

function writeRegistryFile(
  outDir: string,
  outFile: string,
  imports: readonly string[],
  moduleVarNames: readonly string[],
): void {
  const lines: string[] = [
    '// AUTO-GENERATED by scripts/generate-extension-registry.ts — DO NOT EDIT MANUALLY.',
    "import type { PlatformExtension } from '@platform/core-api';",
    ...imports,
    '',
    'function isPlatformExtension(value: unknown): value is PlatformExtension {',
    "  if (!value || typeof value !== 'object') return false;",
    '  const candidate = value as Record<string, unknown>;',
    '  return (',
    "    typeof candidate.manifest === 'object' &&",
    '    candidate.manifest !== null &&',
    "    typeof (candidate.manifest as Record<string, unknown>).id === 'string' &&",
    "    typeof candidate.hooks === 'object' &&",
    '    candidate.hooks !== null',
    '  );',
    '}',
    '',
    'const registry: Record<string, PlatformExtension> = {};',
    `for (const mod of [${moduleVarNames.join(', ')}]) {`,
    '  for (const exportedValue of Object.values(mod)) {',
    '    if (isPlatformExtension(exportedValue)) {',
    '      if (Object.prototype.hasOwnProperty.call(registry, exportedValue.manifest.id)) {',
    '        throw new Error(`DUPLICATE_EXTENSION_ID: Extension "${exportedValue.manifest.id}" is already registered in BUNDLED_TENANT_EXTENSIONS.`);',
    '      }',
    '      registry[exportedValue.manifest.id] = exportedValue;',
    '    }',
    '  }',
    '}',
    '',
    'export const BUNDLED_TENANT_EXTENSIONS: Readonly<Record<string, PlatformExtension>> =',
    '  Object.freeze(registry);',
    '',
  ];

  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
}

export function generateExtensionRegistry(
  options?: GenerateExtensionRegistryOptions,
): GenerateExtensionRegistryResult {
  const repoRoot = options?.repoRoot ?? process.cwd();
  const env = options?.env ?? process.env;
  const argv = options?.argv ?? process.argv;
  const outDir =
    options?.outDir ?? path.join(repoRoot, 'src', 'platform', 'generated');
  const outFile = path.join(outDir, 'extensionRegistry.ts');

  const configured = env.PLATFORM_TENANT_PACKAGE_DIR?.trim();
  const allFixtures = argv.includes('--all-fixtures');

  if (!configured && !allFixtures) {
    writeRegistryFile(outDir, outFile, [], []);
    console.warn(
      'generate-extension-registry: PLATFORM_TENANT_PACKAGE_DIR not set; wrote empty registry.',
    );
    return {
      writtenFile: outFile,
      bundledExtensionIds: [],
    };
  }

  let packageRoots: string[];
  if (configured) {
    const resolvedRoot = path.resolve(repoRoot, configured);
    const baseConfigPath = path.join(resolvedRoot, 'config', 'base.json');
    if (!fs.existsSync(baseConfigPath)) {
      throw new Error(
        `TENANT_CONFIG_ERROR: Tenant configuration file not found at "${baseConfigPath}" for PLATFORM_TENANT_PACKAGE_DIR="${configured}".`,
      );
    }
    packageRoots = [resolvedRoot];
  } else {
    const entries = fs.readdirSync(repoRoot, { withFileTypes: true });
    packageRoots = entries
      .filter((entry) => entry.isDirectory() && entry.name.startsWith('client-'))
      .map((entry) => path.resolve(repoRoot, entry.name))
      .sort()
      .filter((pkgRoot) =>
        fs.existsSync(path.join(pkgRoot, 'config', 'base.json')),
      );
  }

  const platformEnv =
    (env.PLATFORM_ENVIRONMENT as PlatformEnvironment | undefined) ?? 'dev';
  const hostingMode =
    (env.PLATFORM_HOSTING_MODE as HostingMode | undefined) ?? 'multi_tenant';

  const imports: string[] = [];
  const moduleVarNames: string[] = [];
  const bundledExtensionIds: string[] = [];
  const seenExtensionIds = new Set<string>();
  let idx = 0;

  for (const pkgRoot of packageRoots) {
    const baseConfigPath = path.join(pkgRoot, 'config', 'base.json');
    if (!fs.existsSync(baseConfigPath)) {
      throw new Error(
        `TENANT_CONFIG_ERROR: Tenant configuration file not found at "${baseConfigPath}".`,
      );
    }
    const baseConfig = JSON.parse(
      fs.readFileSync(baseConfigPath, 'utf8'),
    ) as Record<string, unknown>;
    const overlayPath = resolveEnvironmentOverlayPath(pkgRoot, platformEnv);
    const overlayConfig = overlayPath
      ? (JSON.parse(fs.readFileSync(overlayPath, 'utf8')) as Record<
          string,
          unknown
        >)
      : {};
    const validatedConfig = loadAndValidateTenantConfig(
      baseConfig,
      overlayConfig,
      platformEnv,
      hostingMode,
    );
    const enabledSet = new Set<string>(validatedConfig.enabledExtensions ?? []);

    const extensionsRoot = path.join(pkgRoot, 'extensions');
    if (!fs.existsSync(extensionsRoot)) continue;

    const extEntries = fs
      .readdirSync(extensionsRoot, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();

    for (const extDirName of extEntries) {
      const extDir = path.join(extensionsRoot, extDirName);
      const manifestPath = path.join(extDir, 'manifest.json');
      if (!fs.existsSync(manifestPath)) continue;

      const rawManifest = JSON.parse(
        fs.readFileSync(manifestPath, 'utf8'),
      ) as Record<string, unknown>;
      const candidateId =
        typeof rawManifest.id === 'string' && rawManifest.id.trim()
          ? rawManifest.id.trim()
          : extDirName;
      if (!enabledSet.has(candidateId) && !enabledSet.has(extDirName)) {
        continue;
      }

      const validated = validateExtensionManifest(rawManifest);
      if (!enabledSet.has(validated.id)) {
        continue;
      }

      if (seenExtensionIds.has(validated.id)) {
        throw new Error(
          `DUPLICATE_EXTENSION_ID: Duplicate extension ID "${validated.id}" encountered while generating extension registry.`,
        );
      }
      seenExtensionIds.add(validated.id);
      bundledExtensionIds.push(validated.id);

      const entryCandidates = [
        path.join(extDir, 'src', 'index.ts'),
        path.join(extDir, 'index.ts'),
        path.join(extDir, 'src', 'index.js'),
        path.join(extDir, 'index.js'),
      ];
      const entryFile = entryCandidates.find((c) => fs.existsSync(c));
      if (!entryFile) {
        throw new Error(
          `EXTENSION_ENTRY_NOT_FOUND: Enabled extension "${validated.id}" in "${extDir}" has no entry module.`,
        );
      }

      const relImport = path
        .relative(outDir, entryFile)
        .replace(/\\/g, '/')
        .replace(/\.(ts|js)$/, '');
      const varName = `extModule_${idx++}`;
      imports.push(`import * as ${varName} from '${relImport}';`);
      moduleVarNames.push(varName);
    }
  }

  writeRegistryFile(outDir, outFile, imports, moduleVarNames);
  return {
    writtenFile: outFile,
    bundledExtensionIds,
  };
}

const isCliMain =
  Boolean(process.argv[1]) &&
  path.resolve(process.argv[1]!) ===
    path.resolve(fileURLToPath(import.meta.url));

if (isCliMain) {
  try {
    generateExtensionRegistry();
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
}
